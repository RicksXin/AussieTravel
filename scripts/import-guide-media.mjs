// Keep the upload inventory in step with newly imported photos; retain the configured host.
const manifestPath = 'data/media-manifest.json'
const manifest = JSON.parse(await fs.readFile(manifestPath, 'utf8'))
const files = {}
for (const name of (await fs.readdir('src/guide-media/h5')).filter(n=>n.endsWith('.jpg')).sort()) {
  const bytes = await fs.readFile(`src/guide-media/h5/${name}`)
  // Dimensions let the detail panel reserve the exact box while a photo downloads, so the
  // layout does not jump. Ratios here range from 0.67 to 1.99, too wide for one fixed box.
  const {width, height} = await sharp(bytes).metadata()
  files[name] = {bytes:bytes.length, sha256:createHash('sha256').update(bytes).digest('hex').slice(0,16), width, height}
}
// New or changed photos are not in cloud storage yet; clear the stamp so the upload is not skipped.
if (JSON.stringify(files)!==JSON.stringify(manifest.files)) manifest.uploadedAt = ''
manifest.files = files
await fs.writeFile(manifestPath, `${JSON.stringify(manifest,null,2)}\n`)
