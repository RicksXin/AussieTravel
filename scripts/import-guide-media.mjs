async function asset(input, name) {
  for (const [platform, width, quality] of [['weapp',560,48],['h5',1100,76]]) {
    const dir = `src/guide-media/${platform}`
    await fs.mkdir(dir, {recursive:true})
    await sharp(input).rotate().resize({width, withoutEnlargement:true}).jpeg({quality, mozjpeg:true}).toFile(`${dir}/${name}`)
  }
  return `/guide-media/${name}`
}
